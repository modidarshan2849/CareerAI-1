import { EducationRecord, SkillEvidence, WorkExperience } from "./types";

const EXTRACTION_SYSTEM_PROMPT = `Extract resume data into compact JSON matching:
{
  "workExperience": [
    {
      "jobTitle": "string",
      "employer": "string",
      "startDate": "YYYY-MM-DD or YYYY or null",
      "endDate": "YYYY-MM-DD or YYYY or null",
      "isCurrent": boolean,
      "responsibilities": ["concise string"],
      "achievements": ["concise string"],
      "technologies": ["string"],
      "employmentType": "full-time | contract | internship | freelance | part-time",
      "leadershipEvidence": ["string"],
      "needsReview": boolean
    }
  ],
  "education": [
    {
      "institution": "string",
      "credential": "string",
      "field": "string or null",
      "graduationDate": "YYYY or null"
    }
  ],
  "skillsListed": ["string"],
  "explicitSkillStatements": [
    { "skillName": "string", "statement": "string" }
  ]
}
Return raw JSON only. Be concise. Never fabricate data.`;

function cleanRawJson(rawText: string): any {
  if (!rawText || !rawText.trim()) throw new Error("Received empty response from AI model.");

  let cleaned = rawText
    .replace(/```json/gi, "")
    .replace(/```/g, "")
    .trim();

  const firstBrace = cleaned.indexOf("{");
  if (firstBrace === -1) throw new Error("No JSON object detected in response.");

  cleaned = cleaned.substring(firstBrace);

  try {
    return JSON.parse(cleaned);
  } catch {
    let openBraces = 0;
    let openBrackets = 0;
    let inString = false;
    let escaped = false;

    for (let i = 0; i < cleaned.length; i++) {
      const char = cleaned[i];
      if (escaped) { escaped = false; continue; }
      if (char === "\\") { escaped = true; continue; }
      if (char === '"') { inString = !inString; continue; }
      if (!inString) {
        if (char === "{") openBraces++;
        else if (char === "}") openBraces--;
        else if (char === "[") openBrackets++;
        else if (char === "]") openBrackets--;
      }
    }

    let repaired = cleaned;
    if (inString) repaired += '"';
    repaired = repaired.replace(/,\s*([}\]])/g, "$1").replace(/,\s*$/, "");

    while (openBrackets > 0) { repaired += "]"; openBrackets--; }
    while (openBraces > 0) { repaired += "}"; openBraces--; }

    try {
      return JSON.parse(repaired);
    } catch {
      throw new Error(`Incomplete JSON generated by model: ${cleaned.slice(-100)}`);
    }
  }
}

function toStringArray(input: any): string[] {
  if (!input) return [];
  if (Array.isArray(input)) {
    return input
      .flatMap((item: any) => (typeof item === "string" ? item.split(/[,•|]/) : [item]))
      .map((item: any) => (typeof item === "object" && item ? item.name || item.skill || item.title || "" : String(item)))
      .map((s: string) => s.trim())
      .filter((s: string) => s.length > 0);
  }
  if (typeof input === "string") {
    return input
      .split(/[,•|\n]/)
      .map((s: string) => s.trim())
      .filter((s: string) => s.length > 0);
  }
  return [];
}

async function extractWithGemini(resumeText: string, apiKey: string): Promise<any> {
  const cleanKey = String(apiKey || process.env.GEMINI_API_KEY || "").trim().replace(/^["']|["']$/g, "");
  const cleanText = String(resumeText || "").trim();

  if (!cleanKey) throw new Error("GEMINI_API_KEY is not configured.");
  if (!cleanText) throw new Error("Resume text is empty.");

  const configuredModels = String(
    process.env.GEMINI_MODELS || "gemini-3.8-flash,gemini-2.5-pro,gemini-flash-latest,gemini-3.8-flash"
  )
    .split(",")
    .map((m: string) => m.trim())
    .filter(Boolean);

  let lastError: Error | null = null;

  for (const model of configuredModels) {
    try {
      const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${cleanKey}`;
      
      const response = await fetch(endpoint, {
        method: "POST",
        headers: {
          "content-type": "application/json",
          "x-goog-api-key": cleanKey,
        },
        body: JSON.stringify({
          systemInstruction: { parts: [{ text: EXTRACTION_SYSTEM_PROMPT }] },
          contents: [{ role: "user", parts: [{ text: cleanText }] }],
          generationConfig: {
            responseMimeType: "application/json",
            maxOutputTokens: 8192,
            temperature: 0.1,
          },
        }),
      });

      if (!response.ok) {
        if (response.status === 429 || response.status === 404) continue;
        lastError = new Error(`Gemini error (${response.status}) on ${model}`);
        continue;
      }

      const data = await response.json();
      const rawText = data.candidates?.[0]?.content?.parts?.map((p: any) => p.text ?? "").join("") ?? "";
      return cleanRawJson(rawText);
    } catch (err: any) {
      lastError = err instanceof Error ? err : new Error(String(err));
    }
  }

  throw lastError || new Error("All available AI models exhausted or offline.");
}

export async function extractProfileFromText(resumeText: string): Promise<{
  workExperience: Array<Omit<WorkExperience, "id">>;
  education: Array<Omit<EducationRecord, "id">>;
  skills: SkillEvidence[];
}> {
  const geminiKey = process.env.GEMINI_API_KEY || "";
  const raw = await extractWithGemini(resumeText, geminiKey);

  const rawWork = Array.isArray(raw?.workExperience) ? raw.workExperience : [];
  const workExperience = rawWork.map((w: any) => {
    const isCurrent =
      Boolean(w.isCurrent) ||
      w.endDate === null ||
      /present|current|now/i.test(String(w.endDate || ""));

    return {
      jobTitle: String(w.jobTitle || "Professional Experience").trim(),
      employer: String(w.employer || "Company / Organization").trim(),
      period: {
        startDate: w.startDate ? String(w.startDate).trim() : null,
        endDate: isCurrent ? null : w.endDate ? String(w.endDate).trim() : null,
        isCurrent,
      },
      responsibilities: toStringArray(w.responsibilities),
      achievements: toStringArray(w.achievements),
      technologies: toStringArray(w.technologies),
      employmentType: (w.employmentType || "full-time") as WorkExperience["employmentType"],
      leadershipEvidence: toStringArray(w.leadershipEvidence),
      source: "extracted",
      needsReview: Boolean(w.needsReview) || !w.jobTitle || !w.employer,
    };
  });

  const rawEdu = Array.isArray(raw?.education) ? raw.education : [];
  const education = rawEdu.map((e: any) => {
    if (typeof e === "string") {
      return {
        institution: e.trim(),
        credential: "Degree / Certificate",
        field: null,
        graduationDate: null,
        source: "extracted",
      };
    }
    return {
      institution: String(e?.institution || "Educational Institution").trim(),
      credential: String(e?.credential || "Degree").trim(),
      field: e?.field ? String(e.field).trim() : null,
      graduationDate: e?.graduationDate ? String(e.graduationDate).trim() : null,
      source: "extracted",
    };
  });

  const rawSkillMentions: RawSkillMention[] = [];

  workExperience.forEach((w: any, index: number) => {
    const roleId = `role_${index}`;
    w.technologies.forEach((skill: string) => {
      rawSkillMentions.push({
        skillName: skill,
        sourceRoleId: roleId,
        sourceRoleTitle: w.jobTitle,
        contextText: `Applied in role: ${w.jobTitle} at ${w.employer}`,
      });
    });
  });

  toStringArray(raw?.skillsListed).forEach((skill: string) => {
    rawSkillMentions.push({
      skillName: skill,
      contextText: "Listed in resume skills section",
    });
  });

  const rawStatements = Array.isArray(raw?.explicitSkillStatements) ? raw.explicitSkillStatements : [];
  const safeStatements: ExplicitSkillStatement[] = rawStatements
    .filter((s: any) => s && typeof s === "object")
    .map((s: any) => ({
      skillName: String(s.skillName || "").trim(),
      statement: String(s.statement || "").trim(),
    }))
    .filter((s: ExplicitSkillStatement) => s.skillName.length > 0);

  const typedWorkExperience: WorkExperience[] = workExperience.map((w: any, index: number) => ({
    id: `role_${index}`,
    jobTitle: w.jobTitle,
    employer: w.employer,
    period: w.period,
    responsibilities: w.responsibilities,
    achievements: w.achievements,
    technologies: w.technologies,
    employmentType: w.employmentType,
    leadershipEvidence: w.leadershipEvidence,
    source: w.source,
    needsReview: w.needsReview,
  }));

  const skills = buildSkillEvidence(rawSkillMentions, safeStatements, typedWorkExperience);

  return {
    workExperience,
    education,
    skills,
  };
}
